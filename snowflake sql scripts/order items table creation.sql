CREATE OR REPLACE TABLE ORDER_ITEMS (
    order_id STRING,
    order_item_id NUMBER,
    product_id STRING,
    seller_id STRING,
    shipping_limit_date TIMESTAMP,
    price NUMBER(10,2),
    freight_value NUMBER(10,2)
);

LIST @ORDERS_STAGE;

COPY INTO MARKETMIND_DB.RETAIL.ORDER_ITEMS
FROM @MARKETMIND_DB.RETAIL.ORDERS_STAGE
FILES = ('olist_order_items_dataset.csv')
FILE_FORMAT = (
    TYPE = CSV
    SKIP_HEADER = 1
    FIELD_DELIMITER = ','
    TRIM_SPACE = TRUE
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    REPLACE_INVALID_CHARACTERS = TRUE
    DATE_FORMAT = 'DD-MM-YYYY'
    TIME_FORMAT = 'HH24:MI'
    TIMESTAMP_FORMAT = 'DD-MM-YYYY HH24:MI'
)
ON_ERROR = ABORT_STATEMENT;

SELECT COUNT(*) AS total_orders
FROM ORDER_ITEMS;

SELECT *
FROM ORDER_ITEMS
LIMIT 10;